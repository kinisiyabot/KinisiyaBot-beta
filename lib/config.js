//  👉 عايز تغيّر الـ API؟ غيّر السطر اللي تحت بس (DEFAULT_API_BASE).
//     كل بلوجنات التنزيل والذكاء الاصطناعي (٣٧ ملف) بتقرأ من هنا عن طريق
//     global.API_BASE، فمش محتاج تلمس أي بلوجن.
//
//  طريقة أسرع بدون تعديل الملف: شغّل البوت بمتغيّر بيئة
//      API_BASE=https://my-api.example.com npm start
//
//  ملاحظة: العنوان القديم (apex) متوقف ويرجع HTTP 402، فبدّله بعنوان شغّال.
// ───────────────────────────────────────────────────────────────────────────

// 👇 غيّر العنوان من هنا فقط
const DEFAULT_API_BASE = 'https://apex-api-five.vercel.app'

// متغيّر البيئة API_BASE له الأولوية إن وُجد.
export const API_BASE = (process.env.API_BASE || DEFAULT_API_BASE)
  .trim()
  .replace(/\/+$/, '')

// متاح كـ global لأن كثيراً من البلوجنات تستخدمه داخل قوالب نصية.
global.API_BASE = API_BASE
